local originalAmmoCategorize = Ammo.categorize

function Ammo:categorize(item, instance)
  local category = originalAmmoCategorize(self, item, instance)

  if item:getModID() ~= "GaelGunStore_B42" then
    return category
  end

  local name = item:getName():lower()
  local recipe = item:getDoubleClickRecipe()

  if name:contains("casing") or name:contains("tip") or (recipe and recipe:contains("casing")) then
    return Ammo.toMaterial(category)
  end

  return category
end
